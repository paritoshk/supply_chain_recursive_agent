/** Multi-seed aggregation + markdown rendering for docs/sim-results.md. Synthetic data only. */
import { round } from "../logic/dates.ts";
import { compareSimulation, HUMAN_MINUTES, type SimComparison, type SimMetrics } from "./simulate.ts";

export interface SimReport {
  label: string;
  generated_for: string;
  days: number;
  primary_seed: number;
  seeds: number[];
  assumptions: Record<string, unknown>;
  primary: SimComparison;
  mean: { baseline: SimMetrics; agent: SimMetrics };
}

function meanMetrics(rows: SimMetrics[]): SimMetrics {
  const keys = Object.keys(rows[0]!) as Array<keyof SimMetrics>;
  return Object.fromEntries(keys.map((k) => [k, round(rows.reduce((s, r) => s + r[k], 0) / rows.length, 2)])) as unknown as SimMetrics;
}

export function buildSimReport(primarySeed: number, seeds: number[], days = 90): SimReport {
  const primary = compareSimulation(primarySeed, days);
  const runs = seeds.map((s) => compareSimulation(s, days));
  return {
    label: "SYNTHETIC SIMULATION: fictional company (Corvane Biologics), synthetic inventory, demand, prices and supplier delays.",
    generated_for: "Supplier Chief of Staff",
    days,
    primary_seed: primarySeed,
    seeds,
    assumptions: {
      demand: "daily rate x (1 + 0.25 * N(0,1)), floored at 0; identical stream for both policies",
      supplier_delays: "15% of approved supplier links get one delay event (+14..35 d for 21..45 d), hitting new and in-flight orders; hero incumbent lead slipped 42 -> 70 d",
      prices: "list price from the hidden persona profile (no negotiation savings assumed for either policy)",
      baseline: "weekly review vs static ROP, primary supplier only, reactive expedite when < 7 d cover",
      agent: "daily sentinel; transfer from sister-site surplus -> expedite in-flight -> RFQ best landed approved option; never non-qualified",
      human_minutes: HUMAN_MINUTES,
      authority_threshold_usd: 25_000,
    },
    primary,
    mean: { baseline: meanMetrics(runs.map((r) => r.baseline.metrics)), agent: meanMetrics(runs.map((r) => r.agent.metrics)) },
  };
}

const fmt = (v: number, d = 0) => v.toLocaleString("en-US", { maximumFractionDigits: d, minimumFractionDigits: d });
const delta = (a: number, b: number) => (a === 0 ? (b === 0 ? "0%" : "n/a") : `${b - a > 0 ? "+" : ""}${fmt(((b - a) / a) * 100, 0)}%`);

const ROWS: Array<[keyof SimMetrics, string, number]> = [
  ["stockout_events", "Stockout events", 0],
  ["stockout_days", "Stockout pair-days", 0],
  ["service_level_pct", "Service level (fill rate, %)", 2],
  ["expedite_spend_usd", "Expedite spend (USD)", 0],
  ["avg_inventory_value_usd", "Avg inventory value (USD)", 0],
  ["purchase_spend_usd", "Purchase spend at list (USD)", 0],
  ["orders", "Purchase orders", 0],
  ["transfers", "Inter-site transfers", 0],
  ["expedites", "Expedites", 0],
  ["human_touches", "Human touches", 0],
  ["human_minutes", "Human minutes", 0],
  ["approval_pings", "Approval pings", 0],
  ["non_qualified_orders", "Orders from non-qualified suppliers", 0],
];

function table(b: SimMetrics, a: SimMetrics, d = 0): string {
  const lines = ["| Metric | Baseline (manual) | Agent | Change |", "|---|---:|---:|---:|"];
  for (const [k, label, digits] of ROWS) lines.push(`| ${label} | ${fmt(b[k], Math.max(digits, d && k !== "service_level_pct" ? 1 : digits))} | ${fmt(a[k], Math.max(digits, d && k !== "service_level_pct" ? 1 : digits))} | ${delta(b[k], a[k])} |`);
  return lines.join("\n");
}

export function renderSimMarkdown(r: SimReport): string {
  const b = r.primary.baseline;
  const a = r.primary.agent;
  const hero = (x: typeof b) =>
    `${x.hero.stockout_days} stockout days${x.hero.first_stockout_day != null ? ` (first on day ${x.hero.first_stockout_day})` : ""}`;
  const heroEvents = (x: typeof b) =>
    x.hero.events
      .filter((e) => e.kind !== "review")
      .slice(0, 8)
      .map((e) => `  - day ${e.day}: ${e.kind}: ${e.detail}`)
      .join("\n") || "  - none";
  return `# Simulation results: manual baseline vs Supplier Chief of Staff

> **${r.label}**
> Not a forecast of real-world performance. Generated by \`pnpm --filter @supply-agent/core sim\` (packages/core/src/sim).

${r.days}-day horizon over ${b.metrics.pairs} material/site positions. Both policies see the same demand stream and the same injected supplier delays (common random numbers); only the decision policy differs.

## Headline (seed ${r.primary_seed})

${table(b.metrics, a.metrics)}

## Mean over ${r.seeds.length} seeds (${r.seeds[0]}..${r.seeds.at(-1)})

${table(r.mean.baseline, r.mean.agent, 1)}

## Hero position (injectable sucrose at Ghent; incumbent lead time slipped to 10 weeks)

- Baseline: ${hero(b)}
${heroEvents(b)}
- Agent: ${hero(a)}
${heroEvents(a)}

## Policies

- **Baseline (manual):** weekly review against a static reorder point (planned lead + safety days), orders only from the primary supplier at its current lead time, reactive expedite when cover drops under 7 days. Human time: ${HUMAN_MINUTES.shortage_review} min per shortage review, ${HUMAN_MINUTES.rfq} min per RFQ, ${HUMAN_MINUTES.transfer} min per transfer.
- **Agent:** daily sentinel and the agent's decision tree: transfer from sister-site surplus first, else expedite an in-flight order, else RFQ the cheapest landed approved supplier that arrives before stock-out (expedited if needed). Never orders from non-qualified or BIOSECURE-flagged suppliers. Human time: ${HUMAN_MINUTES.approval_ping} min per approval ping, only for decisions above USD 25,000 (or unpriced).

## Assumptions

${Object.entries(r.assumptions)
  .map(([k, v]) => `- **${k}:** ${typeof v === "string" ? v : JSON.stringify(v)}`)
  .join("\n")}
`;
}
